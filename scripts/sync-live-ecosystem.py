#!/usr/bin/env python3
"""Generate the portfolio catalogue from authenticated GitHub repository metadata.
Never infer a working deployment from a repository name alone.
"""
import concurrent.futures, json, re, subprocess, urllib.request, urllib.error
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
repos=json.loads(subprocess.check_output(['gh','api','user/repos?per_page=100','--paginate'],text=True))
byname={r['name'].lower():r for r in repos}
extras={
 'Merqalor-credit':('MERQALOR CREDIT','Moteur de risque et scoring crédit','FastAPI,RAROC,Scoring','https://credit.koryxa.fr/cockpit'),
 'koryxa-voicebox-stt':('CAURI / Voice-to-Ledger','De la voix à la transaction comptable','FastAPI,Whisper,STT','https://cauri.koryxa.fr'),
 'koryxa-terminal-bridge':('Terminal Bridge','Exécution contrôlée, GitHub et terminal','Python,GitHub,API',None),
 'koryxa-devbridge-frontend':('DevBridge','Studio de pilotage des agents et jobs','Next.js,Agents,API',None),
 'koryxa-chatlaya':('ChatLaya','Assistant conversationnel KORYXA','LLM,Chat',None),
 'koryxa-virtual-director':('Virtual Director','Direction opérationnelle assistée par IA','IA,Agents',None),
 'finepersoAI':('FinPersoAI','Assistant de finances personnelles','IA,Finance',None),
 'formation-llm-rag-vscode':('Formation LLM RAG','Formation pratique aux systèmes RAG','LLM,RAG,Qdrant',None),
 'EnergiSight.':('EnergiSight','Intelligence et analyse énergétique','Data,Énergie',None),
 'InnovaFinance':('InnovaFinance','Application de finance numérique','Finance,Web',None),
 'myplanning':('MyPlanning','Planification et gestion des disponibilités','Planning,API',None),
 'mataki':('Mataki','Assistant WhatsApp et recherche IA','FastAPI,Next.js,RAG',None),
 'merqalor-frontend':('MERQALOR Platform','Interface de l’écosystème MERQALOR','Next.js,Finance',None),
 'neurokap':('NeuroKap','Plateforme d’entraînement cognitif','Next.js,IA',None),
 'corabiz':('CoraBiz','Assistant commercial et suivi de prospects','SaaS,IA',None),
 'koryxa-services-ia':('KORYXA Services IA','Catalogue de services IA','IA,Web',None),
 'koryxa_formation':('KORYXA Formation','Plateforme de formation KORYXA','Formation,Web',None),
 'koryxa-admin':('KORYXA Admin','Console de gestion privée','Admin,Next.js',None),
 'koryxa-payment-web':('KORYXA Payment','Interface de paiement marchand','Next.js,Paiement',None),
 'koryxa-cora':('KORYXA Cora','Assistant IA et orchestration','IA,Agents',None),
 'koryxa-partner-portal':('KORYXA Partner Portal','Portail partenaire','Web,Formation',None),
 'koryxa-api':('KORYXA API','Portail et passerelle API','API,Web',None),
}
exclude={'lamadokou.yayra','koryxa-terminal-bridge-test','koryxa-terminal-bridge-test-repo','koryxa-devbridge-test-repo','koryxa-gpt-repo-test'}
# Other repos with homepage metadata are included automatically, even when not explicitly curated.
items=[]
for r in repos:
 name=r['name']; homepage=(r.get('homepage') or '').strip()
 if name in exclude:continue
 if name not in extras and not homepage:continue
 title,tagline,stack,override=extras.get(name,(name,r.get('description') or 'Projet de l’écosystème', 'Web',None))
 url=override or (homepage if homepage.startswith('https://') else None)
 items.append(dict(name=title,tagline=tagline,stack=[s.strip() for s in stack.split(',')],url=url,repo=r['html_url'],private=r['private'],source=name))

def check(item):
 if not item['url']:return ('Demo',None)
 try:
  req=urllib.request.Request(item['url'],headers={'User-Agent':'Mozilla/5.0 KORYXA-portfolio-audit'})
  with urllib.request.urlopen(req,timeout=9) as res:
   final=res.geturl()
   if 'accounts.koryxa.fr/sign-in' in final or 'login' in final:return ('Private',res.status)
   return ('Live' if res.status<400 else 'Demo',res.status)
 except urllib.error.HTTPError as e:
  if e.code in (401,403):return ('Private',e.code)
  return ('Demo',e.code)
 except Exception:return ('Demo',None)

with concurrent.futures.ThreadPoolExecutor(max_workers=16) as pool:
 checks=list(pool.map(check,items))
for item,(status,http) in zip(items,checks):
 item['status']=status
 item['http']=http
 # A private repo is distinct from a gated deployment.
items.sort(key=lambda x:({'Live':0,'Private':1,'Demo':2}[x['status']],x['name'].lower()))
public=[{k:v for k,v in i.items() if k not in ('source','http')} for i in items]
(ROOT/'src/data').mkdir(exist_ok=True)
(ROOT/'src/data/projects.ts').write_text('''// Generated by scripts/sync-live-ecosystem.py from authenticated GitHub metadata.
// "Live" means HTTP accessible at scan time; "Private" means access gated.
export type EcosystemProject = {
  name: string;
  tagline: string;
  stack: string[];
  url: string | null;
  repo: string;
  private: boolean;
  status: "Live" | "Private" | "Demo";
};
export const ecosystemProjects: EcosystemProject[] = '''+json.dumps(public,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
readme=['# Yayra Junior Lamadokou — AI Engineer | FastAPI + Next.js + RAG/LLM','','**3,182 contributions / an** · Remote only · Lomé, Togo (GMT/UTC+0) · **TJM : sur demande**','','Ingénieur IA — FastAPI, Next.js, Python, RAG, STT, LLM.','', '## LIVE ECOSYSTEM','', 'Inventaire basé sur les métadonnées GitHub et une vérification HTTP ponctuelle. Un dépôt privé ne signifie pas que sa démonstration est publique.','', '| Projet | Statut | Live / démo | Repo |','| --- | --- | --- | --- |']
for i in items:
 url=f"[Voir Live]({i['url']})" if i['url'] else 'Demo sur demande'
 readme.append(f"| {i['name']} | {i['status']}{' 🔒' if i['private'] else ''} | {url} | [GitHub]({i['repo']}) |")
readme+=['','**Contact :** ylamadokou@gmail.com · **Disponibilité :** missions remote AI Engineer / RAG Engineer · **Fuseau :** GMT (UTC+0).','','**Note :** Le statut Live reflète uniquement la réponse HTTP au moment du scan, pas une validation fonctionnelle de l’application. Les URLs protégées restent cliquables.']
(ROOT/'README.md').write_text('\n'.join(readme)+'\n',encoding='utf-8')
(ROOT/'live-ecosystem-audit.json').write_text(json.dumps(items,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Repositories scanned:',len(repos),'Projects:',len(items),'Live:',sum(i['status']=='Live' for i in items),'Private:',sum(i['status']=='Private' for i in items),'Demo:',sum(i['status']=='Demo' for i in items))
for i in items:print(i['status'],i['name'],i['url'] or 'Demo sur demande',i['http'])
